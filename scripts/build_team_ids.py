#!/usr/bin/env python3
"""Build the API-Football team_id lookup from /teams?league=X&season=2024.

Uses the free plan (100 req/día) for SP1=140, SP2=141, Liga F=142. The free
plan caps seasons at 2022-2024, so we settle for 2024 even for our current
2026/27 quiniela. The mapping is stable enough for H2H calls.

Outputs: scripts/team_ids_api_football.py with a TEAM_IDS dict mapping
canonical_name -> {"id": int, "name": str, "country": str, "league": str}.
"""
from __future__ import annotations

import json
import re
import sys
import unicodedata
import urllib.error
import urllib.request
from pathlib import Path

API_BASE = "https://v3.football.api-sports.io/teams"
LEAGUES = (
    (140, "sp1", "LaLiga"),
    (141, "sp2", "Segunda Division"),
    (142, "liga_f", "Primera Division Femenina"),
)
SEASON = 2024
CACHE = Path("/tmp/la-goyniela-mock")


def _strip_accents(s: str) -> str:
    return "".join(c for c in unicodedata.normalize("NFKD", s)
                   if not unicodedata.combining(c))


def normalize_team_name(name: str) -> str:
    """Stable canonical key used for mapping Odds API / Football-Data names
    to API-Football IDs. Does NOT strip Spanish prefixes like 'real' or
    'atletico' — see SP_CANONICAL in mock_quiniela.py for that.
    """
    s = _strip_accents(name).lower()
    s = re.sub(r"[^a-z0-9 ]+", " ", s)
    return re.sub(r"\s+", " ", s).strip()


def fetch(url: str, key: str) -> dict:
    req = urllib.request.Request(url, headers={"x-apisports-key": key})
    with urllib.request.urlopen(req, timeout=20) as r:
        return json.loads(r.read())


def fetch_or_cache(key: str, league_id: int, label: str) -> list[dict]:
    fpath = CACHE / f"apif_teams_{label}_v2024.json"
    if fpath.exists():
        return json.loads(fpath.read_bytes())["response"]
    data = fetch(f"{API_BASE}?league={league_id}&season={SEASON}", key)
    if data.get("errors"):
        raise SystemExit(f"API-Football errors: {data['errors']}")
    fpath.write_bytes(json.dumps(data).encode())
    return data["response"]


def main() -> int:
    key = sys.argv[1] if len(sys.argv) > 1 else ""
    if not key:
        print("usage: build_team_ids.py <API_FOOTBALL_KEY>", file=sys.stderr)
        return 1

    CACHE.mkdir(parents=True, exist_ok=True)
    team_ids: dict[str, dict] = {}
    for league_id, label, human_name in LEAGUES:
        teams = fetch_or_cache(key, league_id, label)
        for item in teams:
            team = item["team"]
            canon = normalize_team_name(team["name"])
            if canon in team_ids and team_ids[canon]["id"] != team["id"]:
                # Some names repeat across divisions; pick LaLiga > Segunda > Liga F
                if team_ids[canon]["league"] in ("sp1", "LaLiga"):
                    continue
            team_ids[canon] = {
                "id": team["id"],
                "name": team["name"],
                "country": team.get("country", ""),
                "league": human_name,
            }
    print(f"Total equipos: {len(team_ids)}")

    out_path = Path(__file__).resolve().parent / "team_ids_api_football.py"
    with out_path.open("w", encoding="utf-8") as fp:
        fp.write('"""Auto-generated by scripts/build_team_ids.py — DO NOT EDIT BY HAND.\n')
        fp.write('Re-run the script when API-Football expands free-plan seasons.\n')
        fp.write('"""')
        fp.write("\n\n")
        fp.write("# canonical -> {id, name, country, league}\n")
        fp.write("# Source: API-Football /teams?league=140|141|142&season=2024\n")
        fp.write("TEAM_IDS_API_FOOTBALL = ")
        fp.write(json.dumps(team_ids, indent=2, ensure_ascii=False))
        fp.write("\n\n")
        fp.write("LEAGUE_LABELS = {\n")
        fp.write('    140: "LaLiga",\n')
        fp.write('    141: "Segunda Division",\n')
        fp.write('    142: "Primera Division Femenina",\n')
        fp.write("}\n")

    print(f"Wrote: {out_path} ({out_path.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
